const assert = require('node:assert/strict');
require('../js/care.js');
const C = globalThis.Care, start = new Date(2026, 9, 21, 10).getTime();
const state = C.defaults(), t = new C.Tracker(state, start, true);
for (let i = 1; i <= 60; i++) t.sync(start + i * 1000, true);
assert.equal(state.days[C.dayKey(start)], 60000);
t.sync(start + 60000, false);
t.sync(start + 3600000, false);
assert.equal(state.days[C.dayKey(start)], 60000, '后台不计入使用时长');
t.sync(start + 3600000, true);
assert.equal(state.sinceBreak, 0, '后台休息足够久后重新计算连续使用');
state.sinceBreak = 20 * 60000;
t.sync(start + 3600000, true);
assert.equal(t.reason(start + 3600000), 'rest');
assert.equal(t.finishRest(start + 3601000), false);
const used = state.days[C.dayKey(start)];
t.sync(start + 3620000, true);
assert.equal(state.days[C.dayKey(start)], used, '休息倒计时不计入使用时长');
assert.equal(t.finishRest(start + 3620000), true);
state.days[C.dayKey(start)] = 30 * 60000;
assert.equal(t.reason(start), 'daily');
state.dailyMinutes = 0;
assert.equal(t.reason(start), '');
assert.equal(C.toggleEye(state), true);
assert.equal(state.theme, 'warm'); assert.equal(state.font, 'large'); assert.equal(state.breakEnabled, true);
assert.equal(C.toggleEye(state), false);
assert.equal(state.dailyMinutes, 0, '一键切换不修改家长时长上限');
const midnight = new Date(2026, 9, 21, 23, 59, 59).getTime();
const split = C.defaults(), mt = new C.Tracker(split, midnight, true);
mt.sync(midnight + 2000, true);
assert.equal(split.days[C.dayKey(midnight)], 1000);
assert.equal(split.days[C.dayKey(midnight + 2000)], 1000);
const data = { coins: 12, streak: 1, last: '', stars: { g1u0: 2 }, wrong: {}, phonics: {}, care: state };
const text = C.encode(data);
assert.equal(C.decode(text, { coins: 0, streak: 0, last: '', stars: {}, wrong: {}, phonics: {}, care: C.defaults() }).coins, 12);
assert.throws(() => C.decode(text.replace('EnglishQuest', 'AnotherApp'), {}));
assert.throws(() => C.decode('{"app":"EnglishQuest","format":1,"data":{"__proto__":{}}}', {}));
assert.throws(() => C.decode(text.replace('"warm"', '"evil"').replace('"light"', '"evil"'), {}));
const invalid = JSON.parse(text); invalid.data.wrong.apple = { word: 'apple', zh: '<img src=x>' };
assert.throws(() => C.decode(JSON.stringify(invalid), {}));
console.log('护眼与备份通过：前台计时、后台排除、休息、每日上限、跨午夜、一键方案与备份校验。');
